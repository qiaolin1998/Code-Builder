// ==========================================================================
// 全局定义头文件，包含 WinCC 运行时所需的数据结构定义和函数声明
// 如 MSG_RTDATA_STRUCT、MSG_CSDATA_STRUCT、MSG_TEXT_STRUCT 等
// ==========================================================================
#include "GlobalDefinitions.h"

// ==========================================================================
// 函数名: alarmsound
// 功  能: WinCC 报警消息触发函数
//         当报警消息到来(COMING)时，读取报警文本并写入 WinCC 变量，
//         同时置位触发位以通知 VBS 脚本执行后续动作（如播放声音）；
//         当报警消息消失(GOING)时，复位触发位。
// 调用场景: 通常在 WinCC 消息系统的属性 -> "消息" 事件中绑定此函数
// ==========================================================================
void alarmsound()
{
    // ------------------------------------------------------------------
    // 变量声明
    // ------------------------------------------------------------------

    // 消息运行时数据结构
    //   - dwMsgNr:   消息编号（唯一标识一条报警）
    //   - dwMsgState: 消息状态（MSG_STATE_COME=到来, MSG_STATE_GO=消失）
    MSG_RTDATA_STRUCT mRT;

    // 消息配置数据结构（静态配置信息）
    //   - dwTextID[]: 文本ID数组，索引0对应主消息文本的ID
    MSG_CSDATA_STRUCT sM;

    // 消息文本结构
    //   - szText: 存放从文本库中读取的实际报警消息字符串
    MSG_TEXT_STRUCT tMeld;

    // 错误信息结构，用于接收 API 调用时的错误详情
    CMN_ERROR pError;

    // ------------------------------------------------------------------
    // 初始化运行时数据结构，确保所有字段清零
    // 避免残留内存数据导致后续判断异常
    // ------------------------------------------------------------------
    memset(&mRT, 0, sizeof(MSG_RTDATA_STRUCT));

    // ------------------------------------------------------------------
    // 获取当前触发此函数的报警消息的运行时数据
    // MSRTGetMsgRTData 会将当前消息的编号和状态填充到 mRT 中
    // 返回值非零表示成功获取数据
    // ------------------------------------------------------------------
    if (MSRTGetMsgRTData(&mRT, &pError))
    {
        // ============================================================
        // 情况1: 报警消息到来 (COMING)
        //   - 需要获取报警的详细配置和文本内容
        //   - 将文本写入变量供画面显示
        //   - 置位触发位通知 VBS 脚本
        // ============================================================
        if (mRT.dwMsgState == MSG_STATE_COME)
        {
            // 根据消息编号获取该报警的配置数据（包含文本ID等）
            MSRTGetMsgCSData(mRT.dwMsgNr, &sM, &pError);

            // 根据文本ID从 WinCC 文本库中读取实际的报警消息文本
            // 参数1: 语言ID，传0表示使用当前运行语言
            // 参数2: 文本ID（来自配置数据）
            // 参数3: 输出文本结构
            MSRTGetMsgText(0, sM.dwTextID[0], &tMeld, &pError);

            // 将 "alarmComing" 变量置为 TRUE
            // 该变量作为 VBS 脚本的触发条件，VBS 脚本检测到此位变化后
            // 可执行播放报警声音等操作
            SetTagBit("alarmComing", TRUE);

            // 将报警消息文本写入 "alarmText" 变量
            // 画面中的文本控件可绑定此变量来显示报警内容
            SetTagChar("alarmText", tMeld.szText);
        }
        // ============================================================
        // 情况2: 报警消息消失 (GOING)
        //   - 仅需复位触发位，停止声音播放等
        // ============================================================
        else if (mRT.dwMsgState == MSG_STATE_GO)
        {
            // 将 "alarmComing" 变量复位为 FALSE
            // VBS 脚本检测到此位复位后停止播放报警声音
            SetTagBit("alarmComing", FALSE);
        }
    }
}